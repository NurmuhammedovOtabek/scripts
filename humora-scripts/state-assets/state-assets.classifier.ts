const LETTER_BOUNDARY = '(^|\\P{L})';
const LETTER_BOUNDARY_END = '(?=\\P{L}|$)';

// eslint-disable-next-line @typescript-eslint/no-unused-vars
function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const COMPILED_NORMALIZATIONS: Array<[RegExp, string]> = NORMALIZATIONS.map(
  ([pattern, replacement]) => [
    new RegExp(
      LETTER_BOUNDARY + escapeRegex(pattern) + LETTER_BOUNDARY_END,
      'giu',
    ),
    '$1' + replacement,
  ],
);

export function classifyAsset(name: string | null | undefined): AssetType {
  const raw = (name || '').trim();
  if (!raw) return 'other';
  const u = raw.toUpperCase();

  if (SHORT_VEHICLE_NAMES.has(u)) return 'vehicle';
  for (const kw of VEHICLE_KEYWORDS) if (u.includes(kw)) return 'vehicle';
  for (const kw of BUILDING_KEYWORDS) if (u.includes(kw)) return 'building';

  if (raw.length > 40 && raw === raw.toUpperCase()) return 'building';

  return 'other';
}

export function normalizeAssetName(
  name: string | null | undefined,
): string | null {
  const raw = (name || '').trim();
  if (!raw) return null;

  let result = raw;
  for (const [pattern, replacement] of COMPILED_NORMALIZATIONS) {
    result = result.replace(pattern, replacement);
  }

  result = result.replace(/\s+/g, ' ').trim();

  return result === raw ? null : result;
}
